import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { readFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import sharp from 'sharp';

const npmCli = process.env.npm_execpath;
if (!npmCli) throw new Error('Execute pelo npm run test:local.');
const statusText = execFileSync(process.execPath, [npmCli,'exec','--','supabase','status'], {encoding:'utf8',env:{...process.env,SUPABASE_TELEMETRY_DISABLED:'1'}});
const status = JSON.parse(statusText.slice(statusText.indexOf('{')));
const url = status.API_URL;
assert.match(url, /^http:\/\/(127\.0\.0\.1|localhost):\d+$/);
const authHealth = await fetch(`${url}/auth/v1/health`);
assert.equal(authHealth.status,200,'test_auth_servico_local');
console.log('test_auth_servico_local: passou');
const headers = {apikey:status.SERVICE_ROLE_KEY,Authorization:`Bearer ${status.SERVICE_ROLE_KEY}`};
const response = await fetch(`${url}/rest/v1/equipments?select=id,patrimony,category,status,image_url&order=patrimony`, {headers});
assert.equal(response.status, 200, 'test_ca_17_api_catalogo');
const equipment = await response.json();
assert.equal(equipment.length, 12, 'test_ca_17_12_equipamentos');
const seedEnv = {...process.env,SUPABASE_URL:url,SUPABASE_SERVICE_ROLE_KEY:status.SERVICE_ROLE_KEY};
const seedTenant = () => execFileSync(process.execPath, ['scripts/seed-tenant.mjs'], {stdio:'ignore',env:seedEnv});
const seedEquipment = () => execFileSync(process.execPath, ['scripts/seed-equipment.mjs'], {stdio:'ignore',env:seedEnv});
const idsBeforeReseed = new Map(equipment.map((x)=>[x.patrimony,x.id]));
seedTenant();
seedEquipment();
const afterReseedResponse = await fetch(`${url}/rest/v1/equipments?select=id,patrimony&order=patrimony`, {headers});
assert.equal(afterReseedResponse.status,200,'test_ca_17_seed_separado');
const afterReseed = await afterReseedResponse.json();
assert.equal(afterReseed.length,12,'test_ca_17_seed_idempotente_quantidade');
for (const row of afterReseed) assert.equal(row.id,idsBeforeReseed.get(row.patrimony),'test_ca_17_seed_idempotente_ids');
console.log('test_ca_17_seed_separado_idempotente_12_equipamentos: passou');
assert.equal(equipment.filter((x)=>x.status === 'MAINTENANCE').length, 3, 'test_ca_18_manutencao');
assert.equal(equipment.filter((x)=>x.category === 'ACCESSORY').length, 3, 'test_ca_18_cabos_accessory');
assert.deepEqual(equipment.filter((x)=>x.status === 'MAINTENANCE').map((x)=>x.patrimony), ['TI-0004','TI-0007','TI-0010']);
console.log('test_ca_18_categorias_e_manutencao: passou');
const credits = JSON.parse(await readFile(resolve('data/imagens/creditos.json'),'utf8'));
for (const item of equipment) {
  assert.match(item.image_url, /^http:\/\/(127\.0\.0\.1|localhost):\d+\/storage\/v1\/object\/public\/equipamentos\//);
  const imageResponse = await fetch(item.image_url);
  assert.equal(imageResponse.status,200,`test_ca_19_imagem_${item.patrimony}`);
  const meta = await sharp(Buffer.from(await imageResponse.arrayBuffer())).metadata();
  assert.equal(meta.width,800); assert.equal(meta.height,600); assert.equal(meta.format,'jpeg');
  const credit = credits.find((x)=>x.patrimonio === item.patrimony);
  assert.equal(credit.status,'aprovada');
}
console.log('test_ca_19_fotos_pixabay_800x600_storage_local: passou');
const config = await readFile(resolve('..','config.local.js'),'utf8');
assert.match(config,/127\.0\.0\.1|localhost/);
assert.doesNotMatch(config,/SERVICE_ROLE_KEY|sb_secret|service_role/i);
console.log('test_segredos_config_publica_local: passou');
